-- ============================================================
-- COLVY V432 — CUSTOMER PORTAL ("YOUR ACCOUNT"), VERSION 1
--
-- One "Your account" page per business, for its customers: what's coming up,
-- quotes and jobs, orders, payments due, the conversation and their
-- preferences. No passwords: a customer signs in with a one-time code sent to
-- the exact email or mobile on their contact, or arrives from a link the
-- business already sent (a booking or quote link), which gives a shorter
-- session. Each business turns it on and picks the sections
-- (companies.portal_settings). Only the server (service role) reads these.
--
--   portal_codes     one-time sign-in codes (hashed), 10 minutes, 5 tries
--   portal_sessions  signed-in customers (token hashed): 30 days unused for
--                    a code, 24 hours for a link; "Sign out" revokes
--   portal_events    visits, sign-ins and actions, for the pilot numbers
--
-- Safe to run more than once.
-- ============================================================

ALTER TABLE companies ADD COLUMN IF NOT EXISTS portal_settings jsonb;

CREATE TABLE IF NOT EXISTS portal_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  contact_id uuid NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  channel text NOT NULL CHECK (channel IN ('email', 'sms')),
  -- The exact address or number the code went to (lower-cased email, or E.164-ish digits).
  destination text NOT NULL,
  code_hash text NOT NULL,
  attempts int NOT NULL DEFAULT 0,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS portal_codes_lookup ON portal_codes (company_id, destination, created_at DESC);

CREATE TABLE IF NOT EXISTS portal_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  contact_id uuid NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  via text NOT NULL CHECK (via IN ('code', 'link')),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  user_agent text
);
CREATE INDEX IF NOT EXISTS portal_sessions_contact ON portal_sessions (company_id, contact_id);

CREATE TABLE IF NOT EXISTS portal_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  contact_id uuid REFERENCES contacts(id) ON DELETE SET NULL,
  -- visit | code_sent | sign_in | link_sign_in | reply | prefs | open_booking | open_quote | pay | sign_out | duplicate_contacts
  kind text NOT NULL,
  detail jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS portal_events_company ON portal_events (company_id, created_at DESC);

-- Server only: no policies, so the browser's anon key can't read or write them.
ALTER TABLE portal_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE portal_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE portal_events ENABLE ROW LEVEL SECURITY;
