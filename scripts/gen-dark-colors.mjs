// Lists the colour literals used in inline styles (app/ and components/) that
// dark mode remaps, into lib/dark-inline-colors.ts: light backgrounds, dark text
// and light borders, by the style property they're written under. Each becomes
// a [style*="…"] override in components/DarkTheme. Run after adding inline
// colours to style objects:
//   node scripts/gen-dark-colors.mjs
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const files = []
const walk = d => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) { if (!/node_modules|\.next/.test(p)) walk(p) } else if (/\.tsx$/.test(f.name)) files.push(p) } }
walk(path.join(root, 'app')); walk(path.join(root, 'components'))

const full = h => h.length === 4 ? '#' + h.slice(1).split('').map(c => c + c).join('') : h
const lum = h => { const n = parseInt(full(h).slice(1), 16); return (0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255)) / 255 }
const bg = new Set(), text = new Set(), line = new Set()
// A style property, then its value up to the next comma or brace (ternaries included).
const PROP = /\b(background(?:Color)?|color|border(?:Top|Bottom|Left|Right)?(?:Color)?|outline)\s*:\s*([^,}\n]*)/g
const HEX = /['"`](?:\d+(?:\.\d+)?px (?:solid|dashed|dotted) )?(#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6})['"`]/g
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8')
  for (const m of s.matchAll(PROP)) for (const h of m[2].matchAll(HEX)) {
    const k = h[1].toLowerCase(), l = lum(k)
    if (m[1].startsWith('background')) { if (l >= 0.62) bg.add(k) }
    else if (m[1] === 'color') { if (l < 0.42) text.add(k) }
    else if (l >= 0.78) line.add(k)
  }
}
const list = s => JSON.stringify([...s].sort()).replace(/","/g, '", "')
fs.writeFileSync(path.join(root, 'lib/dark-inline-colors.ts'),
  `// Generated by scripts/gen-dark-colors.mjs. Do not edit by hand.\n// Inline-style colours that dark mode remaps (components/DarkTheme), by property.\n\n` +
  `export const DARK_INLINE = {\n  bg: ${list(bg)},\n  text: ${list(text)},\n  line: ${list(line)},\n}\n`)
console.log(`backgrounds ${bg.size}, text ${text.size}, lines ${line.size} (${files.length} files)`)
